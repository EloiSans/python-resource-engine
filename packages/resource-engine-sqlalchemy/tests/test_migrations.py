"""The reference module's migrations build the schema of its code, on SQLite
and PostgreSQL: upgrade, then ``alembic check`` finds nothing to migrate, then
downgrade leaves an empty database."""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect

ROOT = Path(__file__).resolve().parents[3]
INI = ROOT / "examples" / "invoices" / "alembic.ini"


def config() -> Config:
    return Config(str(INI))


def tables(sync_url: str) -> set[str]:
    engine = create_engine(sync_url)
    try:
        return set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


def round_trip(monkeypatch, url: str, sync_url: str) -> None:
    from invoices.infrastructure.persistence import metadata

    monkeypatch.setenv("DATABASE_URL", url)
    command.upgrade(config(), "head")
    assert tables(sync_url) == set(metadata.tables)
    command.check(config())  # raises when the code has changes without a migration
    command.downgrade(config(), "base")
    assert tables(sync_url) == set()


def test_sqlite(tmp_path, monkeypatch):
    db = tmp_path / "invoices.db"
    round_trip(monkeypatch, f"sqlite+aiosqlite:///{db}", f"sqlite:///{db}")


@pytest.mark.emulator("postgres")
def test_postgres(postgres_database, monkeypatch):
    round_trip(monkeypatch, postgres_database, postgres_database)  # psycopg is sync and async


def test_check_notices_a_missing_migration(tmp_path, monkeypatch):
    from invoices.infrastructure.persistence import metadata
    from sqlalchemy import Column, String

    db = tmp_path / "invoices.db"
    monkeypatch.setenv("DATABASE_URL", f"sqlite+aiosqlite:///{db}")
    command.upgrade(config(), "head")
    table = metadata.tables["invoices"]
    column = Column("reference", String(40), nullable=True)
    table.append_column(column)
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="reference"):
            command.check(config())
    finally:
        table._columns.remove(column)  # the shared MetaData goes back to the code's schema
