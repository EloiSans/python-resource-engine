"""Compact project catalogue meant to be read by AI coding agents."""

from __future__ import annotations

from resource_engine_devtools.documentation.model import DocumentationModel


def render_ai_context(model: DocumentationModel) -> str:
    out = [
        f"<!-- generated by resource-engine {model.engine_version}; do not edit -->",
        "## Resources",
    ]
    for r in model.resources:
        crud = [o.name for o in r.operations if o.kind == "crud"]
        out.append(f"- {r.name} ({r.module}) — {r.doc.summary or 'undocumented'}")
        out.append(f"  ops: {', '.join(crud) or '-'}")
        if r.filterable:
            out.append(f"  filterable: {', '.join(r.filterable)}")
        if r.tenant_field:
            out.append(f"  tenant_field: {r.tenant_field}")
        if r.version_field:
            strict = " (required)" if r.require_version else ""
            out.append(f"  version_field: {r.version_field}{strict}")
        if r.restricted_fields:
            out.append(f"  restricted_fields: {', '.join(r.restricted_fields)}")
        if model.audit_resource and not r.audit:
            out.append("  audit: off")
        elif model.audit_resource and (r.audit_reads or r.audit_exclude):
            flags = ["reads"] if r.audit_reads else []
            flags += [f"exclude={'+'.join(r.audit_exclude)}"] if r.audit_exclude else []
            out.append(f"  audit: {', '.join(flags)}")
        if r.state_machine:
            sm = r.state_machine
            edges = "; ".join(f"{t.source}-{t.event}->{t.target}" for t in sm.transitions)
            out.append(f"  state_machine: {sm.qualname} field={sm.state_field}: {edges}")
        if r.actions:
            out.append(
                "  actions: " + ", ".join(f"{a.name}({a.input_schema or ''})" for a in r.actions)
            )
        if r.references:
            out.append(
                "  references: "
                + ", ".join(
                    f"{x.name}={x.field}->{x.resource}(on_delete={x.on_delete})"
                    for x in r.references
                )
            )
        if r.events:
            out.append(
                "  events: "
                + ", ".join(f"{e.name}({', '.join(f.name for f in e.fields)})" for e in r.events)
            )
        if r.documents:
            out.append(
                "  documents: "
                + ", ".join(
                    f"{s.name}[{'|'.join(s.content_types)}"
                    f"{', many' if s.multiple else ''}"
                    f"{', required_for=' + '+'.join(s.required_for) if s.required_for else ''}"
                    f"{', processing' if s.processing else ''}]"
                    for s in r.documents
                )
            )
        if r.hooks:
            out.append("  hooks: " + ", ".join(f"{h.point}={h.name}" for h in r.hooks))
    if model.system_roles:
        out += ["", "## Permissions", "Action names: <resource>:<operation>[:<qualifier>]."]
        out += [f"- system role {r.name}: {', '.join(r.grants)}" for r in model.system_roles]
        out.append("- other permissions are ABAC policies stored in authz_policies (data)")
        out.append(
            "- fields: <resource>:read|write:<field>; hidden fields are omitted, writing a "
            "protected field fails with RE-E706, filtering/sorting by one with RE-E707"
        )
    if any(r.tenant_field for r in model.resources):
        out += [
            "",
            "## Tenancy",
            "- resources with tenant_field are confined to Principal.tenant (other tenants' "
            "records are 404); no tenant -> RE-E708, another tenant -> RE-E709; admin and "
            "system_principal act across tenants and pass tenant= to create",
        ]
    if any(r.version_field for r in model.resources):
        out += [
            "",
            "## Concurrency",
            "- resources with version_field: responses carry ETag; update/transition/action/"
            "delete take expected_version= (HTTP If-Match) and a stale one fails with RE-E105 "
            "(409); require_version makes it mandatory (RE-E106, 428); create starts at 1",
        ]
    if model.audit_resource:
        out += [
            "",
            "## Audit",
            f"- every committed change and refused attempt is stored in {model.audit_resource} "
            "(read-only, sensitive); restricted and audit_exclude fields are logged without values",
        ]
    return "\n".join(out) + "\n"
