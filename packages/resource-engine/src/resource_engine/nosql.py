"""Building blocks for document-store repositories (DynamoDB, Cosmos DB,
Firestore): writes buffered in the unit of work and applied at commit in one
transaction of the store, records encoded as documents, generated ids, and
row filters rewritten without ``not``.

- **Writes at commit:** ``add``, ``update`` and ``delete`` are recorded and
  sent together by ``commit`` (``TransactWriteItems``, a Cosmos transactional
  batch, a Firestore commit), so an operation's writes are all or nothing
  within the store's ``transaction_scope``. Past ``max_writes`` the commit
  fails with ``TransactionTooLarge`` (RE-E012) and nothing is written.
- **Reads see the operation's writes** by id (``get``); ``list`` reads what
  is committed.
- **Versions** are compared by the store when the writes are applied
  (a condition on the version field), so two operations racing on one
  record can't both win: the loser gets ``VersionConflict``.
- **Ids** are generated by type: random 53-bit integers for ``int`` ids (safe
  in JSON), UUIDs for ``UUID``, 32 hex characters for ``str``.
"""

from __future__ import annotations

import dataclasses
import secrets
import types
import typing
import uuid
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Literal

from resource_engine.application.query import ListQuery, Page
from resource_engine.errors import TransactionTooLarge, VersionConflict

# ------------------------------------------------------------------- codec


class DocumentCodec:
    """A model's records as plain documents (dicts of Python values) and back.

    Values keep their Python types (``Decimal``, ``datetime``, ``date``); each
    adapter maps them to its store's types. Decoding validates with pydantic,
    so strings and numbers from the store come back as the model's types.
    """

    def __init__(self, model: type, *, id_field: str = "id") -> None:
        from pydantic import TypeAdapter

        self.model = model
        self.id_field = id_field
        try:
            hints = typing.get_type_hints(model)
        except Exception:  # noqa: BLE001
            hints = {}
        self.id_type = _base_type(hints.get(id_field, str))
        self._fields: dict[str, Any] | None = None
        self._adapter: Any = None
        if dataclasses.is_dataclass(model) and not hasattr(model, "__pydantic_fields__"):
            # field by field, then the constructor: mapped classes (SQLAlchemy) need __init__
            names = [f.name for f in dataclasses.fields(model)]
            self._fields = {n: TypeAdapter(hints.get(n, Any)) for n in names}
        else:
            try:
                self._adapter = TypeAdapter(model)
            except Exception:  # noqa: BLE001 - not a pydantic model or typed class
                self._adapter = None

    def encode(self, entity: Any) -> dict[str, Any]:
        if self._fields is not None:
            return {
                name: adapter.dump_python(getattr(entity, name), mode="python")
                for name, adapter in self._fields.items()
            }
        if self._adapter is not None:
            return self._adapter.dump_python(entity, mode="python")
        return {k: v for k, v in vars(entity).items() if not k.startswith("_")}

    def decode(self, document: Mapping[str, Any]) -> Any:
        if self._fields is not None:
            return self.model(
                **{
                    name: adapter.validate_python(document[name])
                    for name, adapter in self._fields.items()
                    if name in document
                }
            )
        if self._adapter is not None:
            return self._adapter.validate_python(dict(document))
        return self.model(**dict(document))

    def new_id(self) -> Any:
        if self.id_type is int:
            return secrets.randbits(53) or 1
        if self.id_type is uuid.UUID:
            return uuid.uuid4()
        return uuid.uuid4().hex


def _base_type(hint: Any) -> type:
    if typing.get_origin(hint) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(hint) if a is not type(None)]
        hint = args[0] if args else str
    return hint if isinstance(hint, type) else str


# ------------------------------------------------------------------ writes


@dataclass
class Write:
    """One buffered write, applied by the unit of work at commit."""

    kind: Literal["put", "delete"]
    resource: str
    key: Any
    document: dict[str, Any] | None = None
    #: The write creates the record: it fails if the id is taken.
    create: bool = False
    #: Compare-and-set: the stored version must still be this one.
    expected_version: int | None = None
    version_field: str = "version"


def version_conflict(write: Write, current: Any = None) -> VersionConflict:
    if write.create:
        return VersionConflict(
            f"{write.resource} {write.key!r} already exists",
            hint="Retry: another record took the same id.",
            details={"resource": write.resource, "id": write.key, "reason": "already exists"},
        )
    return VersionConflict(
        f"{write.resource} {write.key!r} changed since it was read",
        hint="Reload the record and apply your change again.",
        details={
            "resource": write.resource,
            "id": write.key,
            "expected": write.expected_version,
            "current": current,
            "reason": "version conflict",
        },
    )


class DocumentUnitOfWork:
    """Buffers the writes of its repositories and applies them at ``commit``.

    Subclasses set ``transaction_scope`` and ``max_writes``, hand out
    repositories (``repository``) and send the writes (``apply``)."""

    transactional = True
    transaction_scope: str = "unit_of_work"
    max_writes: int | None = None

    def __init__(self) -> None:
        self.writes: dict[tuple[str, Any], Write] = {}
        self._repositories: dict[str, Any] = {}

    def make_repository(self, resource_name: str) -> Any:  # pragma: no cover - abstract
        raise NotImplementedError

    def repository(self, resource_name: str) -> Any:
        if resource_name not in self._repositories:
            self._repositories[resource_name] = self.make_repository(resource_name)
        return self._repositories[resource_name]

    async def apply(self, writes: Sequence[Write]) -> None:  # pragma: no cover - abstract
        """Send ``writes`` in one transaction; raise ``version_conflict(...)``
        when a condition fails."""
        raise NotImplementedError

    def record(self, write: Write) -> None:
        slot = (write.resource, _hashable(write.key))
        earlier = self.writes.pop(slot, None)
        if earlier is not None:
            if earlier.create and write.kind == "delete":
                return  # created and deleted in the same unit of work: nothing to send
            write.create = write.create or earlier.create
            if earlier.expected_version is not None:
                write.expected_version = earlier.expected_version
        self.writes[slot] = write

    def pending(self, resource: str, key: Any) -> Write | None:
        return self.writes.get((resource, _hashable(key)))

    async def commit(self) -> None:
        writes = list(self.writes.values())
        if not writes:
            return
        if self.max_writes is not None and len(writes) > self.max_writes:
            raise TransactionTooLarge(
                f"{len(writes)} writes in one commit; the store takes {self.max_writes}",
                hint="Split the operation, or move bulk changes to a job.",
                details={"writes": len(writes), "max_writes": self.max_writes},
            )
        await self.apply(writes)
        self.writes.clear()

    async def rollback(self) -> None:
        self.writes.clear()

    async def __aenter__(self) -> Any:
        self.writes.clear()
        self._repositories.clear()
        return self

    async def __aexit__(self, *exc: Any) -> None:
        self.writes.clear()


def _hashable(key: Any) -> Any:
    return key if isinstance(key, (str, int, uuid.UUID)) else repr(key)


class DocumentRepository:
    """A ``Repository`` over a document store: reads from the store (``fetch``,
    ``query``), writes buffered in its ``DocumentUnitOfWork``."""

    supports_conditions = True
    supports_versions = True
    filterable: frozenset[str] | None = None
    sortable: frozenset[str] | None = None
    max_offset: int | None = None

    def __init__(
        self,
        uow: DocumentUnitOfWork,
        resource: str,
        codec: DocumentCodec,
        *,
        version_field: str | None = None,
    ) -> None:
        self.uow = uow
        self.resource = resource
        self.codec = codec
        self.version_field = version_field or "version"

    # -- reads, implemented by the adapter
    async def fetch(self, key: Any) -> dict[str, Any] | None:  # pragma: no cover - abstract
        raise NotImplementedError

    async def query(self, query: ListQuery) -> tuple[list[dict[str, Any]], int]:  # pragma: no cover
        """The page's documents and the total matching."""
        raise NotImplementedError

    # -- the Repository port
    async def get(self, entity_id: Any) -> Any:
        write = self.uow.pending(self.resource, entity_id)
        if write is not None:
            return None if write.kind == "delete" else self.codec.decode(write.document or {})
        document = await self.fetch(entity_id)
        return self.codec.decode(document) if document is not None else None

    async def list(self, query: ListQuery) -> Page[Any]:
        documents, total = await self.query(query)
        return Page([self.codec.decode(d) for d in documents], total, query.offset, query.limit)

    def _key(self, entity: Any) -> Any:
        return getattr(entity, self.codec.id_field)

    async def add(self, entity: Any) -> Any:
        if self._key(entity) is None:
            setattr(entity, self.codec.id_field, self.codec.new_id())
        self.uow.record(
            Write("put", self.resource, self._key(entity), self.codec.encode(entity), create=True)
        )
        return entity

    async def update(self, entity: Any, *, expected_version: int | None = None) -> Any:
        if expected_version is not None:
            setattr(entity, self.version_field, expected_version + 1)
        self.uow.record(
            Write(
                "put",
                self.resource,
                self._key(entity),
                self.codec.encode(entity),
                expected_version=expected_version,
                version_field=self.version_field,
            )
        )
        return entity

    async def delete(self, entity: Any, *, expected_version: int | None = None) -> None:
        self.uow.record(
            Write(
                "delete",
                self.resource,
                self._key(entity),
                self.codec.encode(entity),  # the record deleted (partition keys)
                expected_version=expected_version,
                version_field=self.version_field,
            )
        )


def select(entities: Sequence[Any], query: ListQuery) -> tuple[list[Any], int]:
    """Filter, sort and page records in memory (for stores that read a key
    range or a scan and can't sort): the page and the total matching."""
    from resource_engine.authz.conditions import matches
    from resource_engine.translatable import localise

    def value(entity: Any, name: str) -> Any:
        found = getattr(entity, name, None)
        return localise(found, query.locales) if name in query.translatable else found

    items = [
        e
        for e in entities
        if all(value(e, k) == v for k, v in query.filters.items()) and matches(query.condition, e)
    ]
    for key in reversed(list(query.order_by)):
        name = key.lstrip("-")
        items.sort(
            key=lambda e: (value(e, name) is None, value(e, name)), reverse=key.startswith("-")
        )
    return items[query.offset : query.offset + query.limit], len(items)


# -------------------------------------------------------------- conditions

_NEGATED = {"eq": "ne", "ne": "eq", "lt": "ge", "le": "gt", "gt": "le", "ge": "lt"}


def without_not(node: Any) -> Any:
    """``node`` with ``not`` pushed down to the comparisons (``not lt`` →
    ``ge``, ``not in`` → ``nin``, De Morgan for ``and``/``or``), for stores
    whose queries have no negation. ``not`` stays around ``exists`` and
    ``contains``. Records missing the field compare as in the store."""
    if isinstance(node, bool) or not isinstance(node, Mapping) or len(node) != 1:
        return node
    op, args = next(iter(node.items()))
    if op in ("and", "or"):
        return {op: [without_not(a) for a in args]}
    if op != "not":
        return node
    inner = args
    if isinstance(inner, bool):
        return not inner
    if not isinstance(inner, Mapping) or len(inner) != 1:
        return node
    iop, iargs = next(iter(inner.items()))
    if iop == "not":
        return without_not(iargs)
    if iop in _NEGATED:
        return {_NEGATED[iop]: iargs}
    if iop == "in":
        return {"nin": iargs}
    if iop == "nin":
        return {"in": iargs}
    if iop == "and":
        return {"or": [without_not({"not": a}) for a in iargs]}
    if iop == "or":
        return {"and": [without_not({"not": a}) for a in iargs]}
    return {"not": inner}


def field_of(operand: Any) -> str | None:
    """The record field of an operand (``{"attr": "resource.x"}`` → ``x``)."""
    if isinstance(operand, Mapping) and "attr" in operand:
        path = str(operand["attr"])
        if path.startswith("resource."):
            return path.removeprefix("resource.")
    return None


